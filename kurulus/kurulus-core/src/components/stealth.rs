use crate::components::{StealthZoneType, UnitArchetype};
use bevy::prelude::*;
use serde::{Deserialize, Serialize};

/// Types of stealth as defined in GDD System Overview.
#[derive(Default, Reflect, Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum StealthType {
    /// Terrain-based stealth (forests, tall grass, etc.) — automatic.
    #[default]
    Passive,
    /// Ability-based stealth (Boran's active stealth) — manual activation.
    Active,
    /// Group stealth (5+ units in a zone, unmoving).
    Group,
}

/// Stealth capability of a unit.
#[derive(Component, Reflect, Clone, Debug, Serialize, Deserialize)]
#[reflect(Component)]
pub struct Stealth {
    /// Base stealth level (0.0 = easily spotted, 1.0 = near invisible).
    pub level: f32,
    /// Whether the unit is currently hidden from enemies.
    pub is_hidden: bool,
    /// Timer tracking time since last hidden state change.
    pub hidden_timer: f32,
    /// Ambush zone the unit is currently in (if any).
    pub ambush_zone: Option<Entity>,

    // ── NEW Phase 1 fields ──────────────────────────────────────────────
    /// Entry progression timer (0.0 → 2.0 for full stealth entry).
    pub entry_timer: f32,
    /// Whether unit is in "Ready" state for ambush (auto-attack suppressed).
    pub is_ready: bool,
    /// Type of stealth currently active.
    pub stealth_type: StealthType,
    /// The stealth zone type this unit is currently in (if any).
    pub zone_type: Option<StealthZoneType>,
    /// Whether this unit is in a partially overcrowded zone.
    pub partial_stealth: bool,
}

impl Default for Stealth {
    fn default() -> Self {
        Self::visible()
    }
}

impl Stealth {
    /// A fully visible (non-hidden) state.
    pub fn visible() -> Self {
        Self {
            level: 0.0,
            is_hidden: false,
            hidden_timer: 0.0,
            ambush_zone: None,
            entry_timer: 0.0,
            is_ready: false,
            stealth_type: StealthType::Passive,
            zone_type: None,
            partial_stealth: false,
        }
    }

    /// Hidden state with a given base stealth level.
    pub fn hidden(level: f32) -> Self {
        Self {
            level,
            is_hidden: true,
            hidden_timer: 10.0,
            ambush_zone: None,
            entry_timer: 2.0, // fully entered
            is_ready: false,
            stealth_type: StealthType::Passive,
            zone_type: None,
            partial_stealth: false,
        }
    }
}

/// Detection capability of a unit or structure.
#[derive(Component, Reflect, Clone, Debug, Serialize, Deserialize)]
#[reflect(Component)]
pub struct Detection {
    /// Base detection radius in world units.
    pub radius: f32,
    /// Bonus detection from height (e.g., towers see farther).
    pub height_bonus: f32,
    /// Whether this detector is active.
    pub active: bool,
}

/// Pre-placed ambush zone — units inside auto-hide and deal bonus damage.
#[derive(Component, Reflect, Clone, Debug, Serialize, Deserialize)]
#[reflect(Component)]
pub struct AmbushZone {
    pub owner: Entity,
    pub radius: f32,
    pub bonus_damage: f32,
    pub bonus_morale: f32,
    pub duration: f32,
    pub remaining: f32,
}

/// Noise level generated by a unit's movement or actions.
/// 0.0 = completely silent, 1.0 = very loud.
#[derive(Component, Reflect, Clone, Debug, Serialize, Deserialize)]
#[reflect(Component)]
pub struct NoiseLevel {
    pub noise: f32,
}

impl Default for NoiseLevel {
    fn default() -> Self {
        Self { noise: 0.0 }
    }
}

/// Visibility footprint of a unit for detection purposes.
/// 0.0 = tiny (hard to spot), 1.0 = huge (easy to spot).
#[derive(Component, Reflect, Clone, Debug, Serialize, Deserialize)]
#[reflect(Component)]
pub struct UnitVisibility {
    pub footprint: f32,
}

impl UnitVisibility {
    /// Returns a sensible visibility footprint based on unit archetype.
    pub fn from_archetype(archetype: UnitArchetype) -> Self {
        Self {
            footprint: match archetype {
                UnitArchetype::Scout => 0.2,
                UnitArchetype::BaitRider => 0.25,
                UnitArchetype::LightInfantry => 0.3,
                UnitArchetype::Archer => 0.3,
                UnitArchetype::Worker => 0.3,
                UnitArchetype::LightCavalry => 0.5,
                UnitArchetype::HeavyInfantry => 0.7,
                UnitArchetype::HeavyCavalry => 0.8,
                UnitArchetype::SiegeCrew => 0.9,
            },
        }
    }
}

/// Visual marker for a player-placed ambush zone (before it becomes active).
#[derive(Component, Reflect, Clone, Debug, Serialize, Deserialize)]
#[reflect(Component)]
pub struct AmbushMarker {
    pub position: crate::coord::GridPos,
    pub placed_by: Entity,
}
